#!/usr/bin/env python3
"""
Aggregate section statistics from cleaned enrollment data.

This script:
  1. Reads a cleaned CSV generated by clean_main_table.py.
  2. Aggregates enrollment counts by (course_code, academic_term, section).
  3. Computes for each group:
       - enrolled: total number of students
       - passed: students with course_outcome = 'P'
       - failed: students with course_outcome = 'F'
       - withdrawn: students with course_outcome = 'W'
  4. Writes aggregated statistics to
       data_cleaning_output/section_stats_{timestamp}.csv

Usage:
    python aggregate_section_stats.py cleaned_main_table.csv
"""

import csv
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

# ---- Configuration constants -------------------------------------------------

OUTPUT_DIR_NAME = "data_cleaning_output"
OUTPUT_FILE_PREFIX = "section_stats_"
OUTPUT_TIMESTAMP_FORMAT = "%Y%m%d_%H%M%S"
OUTPUT_FILE_EXTENSION = ".csv"

# Input column names (from clean_main_table.py output)
INPUT_COLUMN_COURSE_CODE = "course_code"
INPUT_COLUMN_ACADEMIC_TERM = "academic_term"
INPUT_COLUMN_SECTION = "section"
INPUT_COLUMN_COURSE_OUTCOME = "course_outcome"

# Output column names
OUTPUT_COLUMN_COURSE_CODE = "course_code"
OUTPUT_COLUMN_ACADEMIC_TERM = "academic_term"
OUTPUT_COLUMN_SECTION = "section"
OUTPUT_COLUMN_ENROLLED = "enrolled"
OUTPUT_COLUMN_PASSED = "passed"
OUTPUT_COLUMN_FAILED = "failed"
OUTPUT_COLUMN_WITHDRAWN = "withdrawn"

# Course outcome values
OUTCOME_PASSED = "P"
OUTCOME_FAILED = "F"
OUTCOME_WITHDRAWN = "W"


# ---- Data structures ---------------------------------------------------------


@dataclass
class SectionStats:
    """Mutable container for accumulating section statistics."""

    passed: int = 0
    failed: int = 0
    withdrawn: int = 0

    @property
    def enrolled(self) -> int:
        """Total enrolled is the sum of all outcomes."""
        return self.passed + self.failed + self.withdrawn

    def add_outcome(self, outcome: str) -> None:
        """Increment the appropriate counter based on outcome."""
        if outcome == OUTCOME_PASSED:
            self.passed += 1
        elif outcome == OUTCOME_FAILED:
            self.failed += 1
        elif outcome == OUTCOME_WITHDRAWN:
            self.withdrawn += 1


@dataclass(frozen=True)
class SectionStatsRow:
    """Immutable representation of a section statistics row for CSV output."""

    course_code: str
    academic_term: str
    section: str
    enrolled: int
    passed: int
    failed: int
    withdrawn: int

    def to_dict(self) -> Dict[str, str]:
        """Convert the stats row to a dict suitable for CSV writing."""
        return {
            OUTPUT_COLUMN_COURSE_CODE: self.course_code,
            OUTPUT_COLUMN_ACADEMIC_TERM: self.academic_term,
            OUTPUT_COLUMN_SECTION: self.section,
            OUTPUT_COLUMN_ENROLLED: str(self.enrolled),
            OUTPUT_COLUMN_PASSED: str(self.passed),
            OUTPUT_COLUMN_FAILED: str(self.failed),
            OUTPUT_COLUMN_WITHDRAWN: str(self.withdrawn),
        }


# ---- Aggregation key type ----------------------------------------------------

AggregationKey = Tuple[str, str, str]  # (course_code, academic_term, section)


# ---- Aggregation logic -------------------------------------------------------


def aggregate_by_section(
    rows: Iterable[Dict[str, str]],
) -> Dict[AggregationKey, SectionStats]:
    """Aggregate enrollment counts by (course_code, academic_term, section).

    Args:
        rows: Iterable of row dicts from the cleaned CSV.

    Returns:
        Dictionary mapping each (course_code, academic_term, section) tuple
        to its accumulated SectionStats.
    """
    stats_by_key: Dict[AggregationKey, SectionStats] = {}

    for row in rows:
        course_code = row.get(INPUT_COLUMN_COURSE_CODE, "").strip()
        academic_term = row.get(INPUT_COLUMN_ACADEMIC_TERM, "").strip()
        section = row.get(INPUT_COLUMN_SECTION, "").strip()
        outcome = row.get(INPUT_COLUMN_COURSE_OUTCOME, "").strip()

        # Skip rows with missing key fields
        if not course_code or not academic_term or not section:
            continue

        key: AggregationKey = (course_code, academic_term, section)

        if key not in stats_by_key:
            stats_by_key[key] = SectionStats()

        stats_by_key[key].add_outcome(outcome)

    return stats_by_key


def stats_dict_to_sorted_rows(
    stats_by_key: Dict[AggregationKey, SectionStats],
) -> List[SectionStatsRow]:
    """Convert aggregated stats dict to a sorted list of output rows.

    Rows are sorted by (course_code, academic_term, section) for consistent
    output ordering.

    Args:
        stats_by_key: Dictionary from aggregate_by_section().

    Returns:
        List of SectionStatsRow objects sorted by key.
    """
    sorted_keys = sorted(stats_by_key.keys())

    result: List[SectionStatsRow] = []
    for key in sorted_keys:
        course_code, academic_term, section = key
        stats = stats_by_key[key]

        row = SectionStatsRow(
            course_code=course_code,
            academic_term=academic_term,
            section=section,
            enrolled=stats.enrolled,
            passed=stats.passed,
            failed=stats.failed,
            withdrawn=stats.withdrawn,
        )
        result.append(row)

    return result


# ---- I/O helpers -------------------------------------------------------------


def read_cleaned_csv(input_path: Path) -> Iterable[Dict[str, str]]:
    """Read rows from the cleaned CSV using csv.DictReader.

    Assumes the cleaned CSV uses standard comma delimiter and UTF-8 encoding.
    """
    with input_path.open("r", encoding="utf-8", newline="") as input_file:
        reader = csv.DictReader(input_file)
        for row in reader:
            yield row


def write_stats_csv(
    stats_rows: Iterable[SectionStatsRow],
    output_path: Path,
) -> None:
    """Write section statistics rows to the output CSV."""
    fieldnames: List[str] = [
        OUTPUT_COLUMN_COURSE_CODE,
        OUTPUT_COLUMN_ACADEMIC_TERM,
        OUTPUT_COLUMN_SECTION,
        OUTPUT_COLUMN_ENROLLED,
        OUTPUT_COLUMN_PASSED,
        OUTPUT_COLUMN_FAILED,
        OUTPUT_COLUMN_WITHDRAWN,
    ]

    with output_path.open("w", encoding="utf-8", newline="") as output_file:
        writer = csv.DictWriter(output_file, fieldnames=fieldnames)
        writer.writeheader()

        for stats_row in stats_rows:
            writer.writerow(stats_row.to_dict())


def build_output_path(base_directory: Path) -> Path:
    """Build the output CSV path with a timestamped file name."""
    timestamp = datetime.now().strftime(OUTPUT_TIMESTAMP_FORMAT)
    file_name = f"{OUTPUT_FILE_PREFIX}{timestamp}{OUTPUT_FILE_EXTENSION}"
    return base_directory / file_name


# ---- Orchestration -----------------------------------------------------------


def aggregate_section_stats(
    input_path: Path,
    output_dir: Optional[Path] = None,
) -> Tuple[Path, int, int]:
    """Aggregate section statistics and return stats.

    Args:
        input_path: Path to the cleaned enrollments CSV file.
        output_dir: Optional output directory. Defaults to OUTPUT_DIR_NAME.

    Returns:
        (output_path, total_input_rows, total_aggregated_sections)
    """
    if output_dir is None:
        output_dir = Path(OUTPUT_DIR_NAME)
    output_dir.mkdir(parents=True, exist_ok=True)

    output_path = build_output_path(output_dir)

    # Read all rows to enable counting
    input_rows = list(read_cleaned_csv(input_path))
    total_input_rows = len(input_rows)

    # Aggregate by section
    stats_by_key = aggregate_by_section(input_rows)
    total_aggregated_sections = len(stats_by_key)

    # Convert to sorted output rows
    stats_rows = stats_dict_to_sorted_rows(stats_by_key)

    # Write output
    write_stats_csv(stats_rows, output_path)

    return output_path, total_input_rows, total_aggregated_sections


def main(argv: List[str]) -> None:
    """Command-line entry point.

    Usage:
        python aggregate_section_stats.py <cleaned_csv_path>
    """
    if len(argv) != 2:
        raise ValueError(
            "Usage: python aggregate_section_stats.py <cleaned_csv_path>"
        )

    input_csv_path = Path(argv[1]).expanduser().resolve()
    if not input_csv_path.is_file():
        raise FileNotFoundError(
            f"Input file does not exist: {input_csv_path}"
        )

    (
        output_path,
        total_input_rows,
        total_aggregated_sections,
    ) = aggregate_section_stats(input_csv_path)

    print(f"Input rows processed:           {total_input_rows}")
    print(f"Unique sections aggregated:     {total_aggregated_sections}")
    print(f"Section stats CSV written to:   {output_path}")


if __name__ == "__main__":
    main(sys.argv)
